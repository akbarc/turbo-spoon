
CREATE VIEW PUVIEWEXCISETRANSACTION AS
SELECT     DBO.[TRANSACTION].TRANSACTIONNUMBER,
           DBO.[TRANSACTION].TIME,
           DBO.[TRANSACTION].BATCHNUMBER,
           DBO.[TRANSACTION].CUSTOMERID,
           DBO.[TRANSACTION].CASHIERID,
           DBO.[TRANSACTION].TOTAL, 
           DBO.TRANSACTIONENTRY.TRANSACTIONNUMBER AS TETNUMBER, 
           DBO.TRANSACTIONENTRY.ITEMID, 
           DBO.TRANSACTIONENTRY.FULLPRICE,
           DBO.TRANSACTIONENTRY.COST, 
           DBO.TRANSACTIONENTRY.PRICE, 
           DBO.TRANSACTIONENTRY.QUANTITY, 
           DBO.TRANSACTIONENTRY.DETAILID, 
           DBO.TRANSACTIONENTRY.COMMENT,
           DBO.TRANSACTIONENTRY.TRANSACTIONTIME,
           DBO.TRANSACTIONENTRY.PRICESOURCE, 
           DBO.PUEXCISEENTRY.TRANSACTIONNUMBER AS PUETNUMBER,
           DBO.PUEXCISEENTRY.TRANSACTIONENTRYID AS PUETRANSACTIONENTRYID, 
           DBO.PUEXCISEENTRY.FULLPRICE AS PUEFULLPRICE, 
           DBO.PUEXCISEENTRY.PRICE AS PUEPRICE,
           DBO.PUEXCISEENTRY.COST AS PUECOST, 
           DBO.PUEXCISEENTRY.PRICEA AS PUEPRICEA, 
           DBO.PUEXCISEENTRY.PRICEB AS PUEPRICEB, 
           DBO.PUEXCISEENTRY.PRICEC AS PUEPRICEC,
           DBO.PUEXCISEENTRY.QUANTITY AS PUEQUANTITY, 
           DBO.PUEXCISEENTRY.SALESTAX AS PUESALESTAX, 
           DBO.PUEXCISEENTRY.ITEMID AS PUEITEMID,
           DBO.PUEXCISEENTRY.WEIGHT AS PUEWEIGHT, 
           DBO.PUEXCISEENTRY.TAREWEIGHT AS PUETAREWEIGH, 
           DBO.PUEXCISEENTRY.SUBDESCRIPTION1 AS PUESUBDESCRIPTION1,
           DBO.PUEXCISEENTRY.SUBDESCRIPTION2 AS PUESUBDESCRIPTION2, 
           DBO.PUEXCISEENTRY.SUBDESCRIPTION3 AS PUESUBDESCRIPTION3,
           DBO.PUEXCISEENTRY.TRANSACTIONTIME AS PUETRANSACTIONTIME, 
           DBO.CUSTOMER.ID AS CUID, 
           DBO.CUSTOMER.FIRSTNAME, 
           DBO.CUSTOMER.LASTNAME,
           DBO.CUSTOMER.ACCOUNTNUMBER, 
           DBO.CUSTOMER.COMPANY, 
           DBO.CUSTOMER.CUSTOMTEXT1, 
           DBO.CUSTOMER.CUSTOMTEXT2, 
           DBO.CUSTOMER.CUSTOMTEXT3,
           DBO.CUSTOMER.ACCOUNTBALANCE, 
           DBO.CUSTOMER.TAXEXEMPT, 
           DBO.CUSTOMER.TAXNUMBER, 
           DBO.CUSTOMER.PHONENUMBER, 
           DBO.ITEM.ITEMLOOKUPCODE, 
           DBO.ITEM.DESCRIPTION,
           DBO.ITEM.PRICE AS IPRICE, 
           DBO.ITEM.PRICEA AS IPRICEA, 
           DBO.ITEM.PRICEB AS IPRICEB, 
           DBO.ITEM.PRICEC AS IPRICEC, 
           DBO.ITEM.COST AS ICOST,
           DBO.ITEM.TAREWEIGHT AS ITAREWEIGHT, 
           DBO.ITEM.SUBDESCRIPTION1 AS ISUBDESCRIPTION1, 
           DBO.ITEM.SUBDESCRIPTION2 AS ISUBDESCRIPTION2,
           DBO.ITEM.SUBDESCRIPTION3 AS ISUBDESCRIPTION3, 
           DBO.ITEM.UNITOFMEASURE AS IUNITOFMEASURE, 
           DBO.ITEM.WEIGHT AS IWEIGHT, 
           DBO.DEPARTMENT.NAME AS DNAME,
           DBO.DEPARTMENT.CODE AS DCODE, 
           DBO.CATEGORY.NAME AS CNAME, 
           DBO.CATEGORY.CODE AS CCODE, 
           DBO.SUPPLIER.SUPPLIERNAME, 
           DBO.CASHIER.NUMBER AS CASHIERNUMBER,
           DBO.CASHIER.NAME AS CASHIERNAME, 
           DBO.REGISTER.NUMBER AS REGNUMBER
FROM         DBO.DEPARTMENT RIGHT OUTER JOIN
                      DBO.ITEM LEFT OUTER JOIN
                      DBO.SUPPLIER ON DBO.ITEM.SUPPLIERID = DBO.SUPPLIER.ID LEFT OUTER JOIN
                      DBO.CATEGORY ON DBO.ITEM.CATEGORYID = DBO.CATEGORY.ID ON DBO.DEPARTMENT.ID = DBO.ITEM.DEPARTMENTID RIGHT OUTER JOIN
                      DBO.PUEXCISEENTRY INNER JOIN
                      DBO.TRANSACTIONENTRY ON DBO.PUEXCISEENTRY.TRANSACTIONENTRYID = DBO.TRANSACTIONENTRY.ID ON DBO.ITEM.ID = DBO.TRANSACTIONENTRY.ITEMID LEFT OUTER JOIN
                      DBO.BATCH LEFT OUTER JOIN
                      DBO.REGISTER ON DBO.BATCH.REGISTERID = DBO.REGISTER.ID RIGHT OUTER JOIN
                      DBO.[TRANSACTION] ON DBO.BATCH.BATCHNUMBER = DBO.[TRANSACTION].BATCHNUMBER LEFT OUTER JOIN
                      DBO.CASHIER ON DBO.[TRANSACTION].CASHIERID = DBO.CASHIER.ID LEFT OUTER JOIN
                      DBO.CUSTOMER ON DBO.[TRANSACTION].CUSTOMERID = DBO.CUSTOMER.ID ON DBO.TRANSACTIONENTRY.TRANSACTIONNUMBER = DBO.[TRANSACTION].TRANSACTIONNUMBER
